using System.Text.Json.Nodes;
using Gorynych.Acp.Hosting;

namespace Gorynych.Service;

/// <summary>
/// Durable mailbox state. Pending entries are never evicted to make room for new ones.
/// Callers must authenticate addresses before using them here.
/// </summary>
internal sealed partial class MailboxStore
{
    internal const int MaxTextLength = 32000;
    readonly string path;
    int capacity;
    internal int CapacityForTests { set { if (value <= 0) throw new ArgumentOutOfRangeException(nameof(value)); lock (gate) capacity = value; } }
    readonly TimeProvider clock;
    readonly Lock gate = new();
    JsonArray entries;
    long next;
    long trimmedThrough;
    internal Action<string, string> WriteFile { get; set; } = static (path, json) => AtomicFile.WriteAllText(path, json);

    internal MailboxStore(string path, int capacity = 5000, int waitCapacity = 1000, TimeProvider? clock = null, int assignmentCapacity = 1000)
    {
        this.path = path;
        this.clock = clock ?? TimeProvider.System;
        this.capacity = capacity > 0 ? capacity : throw new ArgumentOutOfRangeException(nameof(capacity));
        this.waitCapacity = waitCapacity > 0 ? waitCapacity : throw new ArgumentOutOfRangeException(nameof(waitCapacity));
        this.assignmentCapacity = assignmentCapacity > 0 ? assignmentCapacity : throw new ArgumentOutOfRangeException(nameof(assignmentCapacity));
        if (File.Exists(path))
        {
            var root = JsonNode.Parse(File.ReadAllText(path))?.AsObject() ?? throw new InvalidDataException("Invalid mailbox state");
            entries = root["entries"]?.AsArray() ?? throw new InvalidDataException("Missing mailbox entries");
            next = (long?)root["next"] ?? throw new InvalidDataException("Missing mailbox sequence");
            trimmedThrough = (long?)root["trimmedThrough"] ?? 0;
            if (root["replyWaits"] is { } retained) replyWaits = retained.AsObject();
            if (root["assignments"] is { } existingAssignments) assignments = existingAssignments.AsObject();
        }
        else entries = [];
    }

    // requestId is generated by the trusted transport and reused on retry. An existing ID
    // cannot be reused with different contents, including a different sender or recipient.
    internal JsonObject Accept(string requestId, string sender, string recipient, string text, string? replyTo = null,
        bool approvedFullAccess = false, bool delegation = false, bool expectReply = false, ReplyReminderSchedule? schedule = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(requestId);
        ArgumentException.ThrowIfNullOrWhiteSpace(sender);
        ArgumentException.ThrowIfNullOrWhiteSpace(recipient);
        ArgumentException.ThrowIfNullOrWhiteSpace(text);
        if (requestId.Length > 256 || sender.Length > 512 || recipient.Length > 512 || replyTo?.Length > 256)
            throw new ArgumentException("Mailbox address or message ID is too long");
        if (text.Length > MaxTextLength) throw new ArgumentException($"Message exceeds {MaxTextLength} characters", nameof(text));
        if (expectReply && (replyTo is not null || delegation || sender == recipient || sender == "service" ||
            sender.StartsWith("outside:", StringComparison.Ordinal) || recipient.StartsWith("outside:", StringComparison.Ordinal)))
            throw new ArgumentException("Only a new message between managed peers can request a reply");
        lock (gate)
        {
            if (FindRetry(requestId, sender, recipient, text, replyTo, delegation, expectReply) is { } retry)
                return retry;
            if (replyTo is not null)
            {
                var original = AddressOf(replyTo);
                if (original?.Recipient != sender || original?.Sender != recipient)
                    throw new InvalidOperationException("Reply does not belong to this recipient");
            }
            // Retain the newest delivered messages while space is available. A pending message is
            // never discarded. A retained reply wait can still correlate after this history expires.
            var replacement = entries.DeepClone().AsArray();
            var trimmed = trimmedThrough;
            while (replacement.Count >= capacity)
            {
                var evict = replacement.OfType<JsonObject>().FirstOrDefault(e => (bool?)e["delivered"] == true);
                if (evict is null) throw new InvalidOperationException("Mailbox storage is full of pending messages");
                trimmed = Math.Max(trimmed, (long)evict["sequence"]!);
                replacement.Remove(evict);
            }
            var item = new JsonObject { ["id"] = requestId, ["sequence"] = next + 1, ["sender"] = sender,
                ["recipient"] = recipient, ["text"] = text, ["replyTo"] = replyTo, ["delivered"] = false,
                ["approvedFullAccess"] = approvedFullAccess };
            if (delegation) { item["delegation"] = true; item["assignmentId"] = requestId; item["assignmentGeneration"] = Guid.NewGuid().ToString("N"); }
            if (expectReply) item["expectReply"] = true;
            replacement.Add((JsonNode)item);
            var waits = AdmitOrResolveWait(requestId, sender, recipient, text, replyTo, expectReply, schedule);
            var admitted = delegation ? AdmitAssignment(requestId, sender, recipient, text, (string)item["assignmentGeneration"]!) : null;
            Save(replacement, next + 1, trimmed, waits, admitted);
            return item.DeepClone().AsObject();
        }
    }

    // Only inspects retained identities under the mailbox lock; never admits a message.
    // A missing result requires the caller to perform the full admission path.
    internal string? TryRetry(string requestId, string sender, string targetOrMessage, string text,
        bool reply, bool delegation = false, bool expectReply = false)
    {
        lock (gate)
        {
            if (!reply && delegation && assignments[requestId] is not null)
            {
                if (FindRetry(requestId, sender, targetOrMessage, text, null, delegation, expectReply) is null)
                    throw new InvalidOperationException("The retained assignment identity is no longer available for retry");
                return targetOrMessage;
            }
            if (AddressOf(requestId) is not { } existing) return null;
            var target = reply ? existing.Recipient : targetOrMessage;
            if (FindRetry(requestId, sender, target, text, reply ? targetOrMessage : null, delegation, expectReply) is null)
                throw new InvalidOperationException("The retained message identity is no longer available for retry");
            return target;
        }
    }

    // Caller holds gate. Validation is shared by retry-only and ordinary admission paths.
    JsonObject? FindRetry(string requestId, string sender, string recipient, string text, string? replyTo,
        bool delegation, bool expectReply)
    {
        var existing = entries.OfType<JsonObject>().FirstOrDefault(e => (string?)e["id"] == requestId);
        if (existing is not null)
        {
            if ((string?)existing["sender"] != sender || (string?)existing["recipient"] != recipient ||
                (string?)existing["text"] != text || (string?)existing["replyTo"] != replyTo ||
                ((bool?)existing["delegation"] == true) != delegation || ((bool?)existing["expectReply"] == true) != expectReply)
                throw new InvalidOperationException("Message ID is already used for another message");
            if (expectReply && replyWaits[requestId] is null)
                throw new InvalidOperationException("The reply wait has expired; its expectation cannot be recreated by retrying the old request.");
            return existing.DeepClone().AsObject();
        }
        if (assignments[requestId] is JsonObject assignment)
        {
            if (!delegation || expectReply || replyTo is not null || (string?)assignment["parent"] != sender ||
                (string?)assignment["child"] != recipient || (string?)assignment["fingerprint"] != WaitFingerprint(text))
                throw new InvalidOperationException("Message ID is already used for another message");
            return new JsonObject { ["id"] = requestId, ["assignmentId"] = requestId, ["sender"] = sender, ["recipient"] = recipient };
        }
        if (replyWaits[requestId] is JsonObject retained)
        {
            if (!expectReply || (string?)retained["sender"] != sender || (string?)retained["recipient"] != recipient ||
                (string?)retained["fingerprint"] != WaitFingerprint(text))
                throw new InvalidOperationException("Message ID is already used for another message");
            return new JsonObject { ["id"] = requestId, ["sender"] = sender, ["recipient"] = recipient };
        }
        var firstReply = FindResolvingReply(requestId);
        if (firstReply.Value is { } resolved)
        {
            if (delegation || expectReply || replyTo != firstReply.Key || (string?)resolved["recipient"] != sender ||
                (string?)resolved["sender"] != recipient || (string?)resolved["replyFingerprint"] != WaitFingerprint(text))
                throw new InvalidOperationException("Message ID is already used for another message");
            return new JsonObject { ["id"] = requestId, ["sender"] = sender, ["recipient"] = recipient };
        }
        return null;
    }

    internal IReadOnlyList<JsonObject> Read(string recipient, long after, int limit, bool pendingOnly = false)
    {
        if (after < 0 || limit is < 1 or > 100) throw new ArgumentOutOfRangeException(nameof(limit));
        lock (gate)
            return entries.OfType<JsonObject>().Where(e => (string?)e["recipient"] == recipient && (long?)e["sequence"] > after &&
                (!pendingOnly || (bool?)e["delivered"] != true)).Take(limit).Select(e => e.DeepClone().AsObject()).ToArray();
    }

    internal JsonObject? Find(string id)
    {
        lock (gate) return entries.OfType<JsonObject>().FirstOrDefault(e => (string?)e["id"] == id)?.DeepClone().AsObject();
    }

    internal long TrimmedThrough { get { lock (gate) return trimmedThrough; } }

    // Advancing a cursor acknowledges the caller's previous page. Merely generating or
    // losing a receive response never acknowledges its messages.
    internal void Acknowledge(string recipient, long through)
    {
        lock (gate)
        {
            if (!entries.OfType<JsonObject>().Any(e => (string?)e["recipient"] == recipient &&
                (long)e["sequence"]! <= through && (bool?)e["delivered"] != true)) return;
            var replacement = entries.DeepClone().AsArray();
            foreach (var item in replacement.OfType<JsonObject>().Where(e => (string?)e["recipient"] == recipient && (long)e["sequence"]! <= through))
                item["delivered"] = true;
            Save(replacement, next);
        }
    }

    internal string[] PendingRecipients()
    {
        lock (gate) return entries.OfType<JsonObject>().Where(e => (bool?)e["delivered"] != true)
            .Select(e => (string)e["recipient"]!).Distinct(StringComparer.Ordinal).ToArray();
    }

    // A persisted claim precedes handing a prompt to a host. Recovery must treat a claim as
    // uncertain, since a crash can occur on either side of the host accepting that prompt.
    internal void MarkStarted(string id, string recipient)
    {
        if (!TryMarkStarted(id, recipient)) throw new InvalidOperationException("Assignment was cancelled before dispatch");
    }

    internal bool TryMarkStarted(string id, string recipient, long? expectedSequence = null)
    {
        lock (gate)
        {
            if (assignments[id] is JsonObject assignment && (string?)assignment["status"] == "cancelled" &&
                (string?)assignment["delivery"] == "suppressed") return false;
            var copy = entries.DeepClone().AsArray();
            var item = copy.OfType<JsonObject>().FirstOrDefault(e => (string?)e["id"] == id && (string?)e["recipient"] == recipient);
            if (expectedSequence is not null && (long?)item?["sequence"] != expectedSequence) return false;
            if (item is null) throw new InvalidOperationException("Unknown message for recipient");
            if ((bool?)item["started"] == true) return true;
            item["started"] = true;
            var updated = WithAssignmentDelivery(id, "started");
            Save(copy, next, waits: WithWaitDelivery(item, "handoff_started"), assigned: updated);
            return true;
        }
    }

    internal void MarkDelivered(string id, string recipient)
        => SetFlag(id, recipient, "delivered");

    internal bool MarkFailed(string id, string recipient, string reason, string? notify = null, bool uncertain = false, long? expectedSequence = null)
    {
        if (reason.Length > MaxTextLength - 1500) reason = reason[..(MaxTextLength - 1500)] + "...";
        lock (gate)
        {
            var copy = entries.DeepClone().AsArray();
            var item = copy.OfType<JsonObject>().FirstOrDefault(e => (string?)e["id"] == id && (string?)e["recipient"] == recipient);
            if (expectedSequence is not null && (long?)item?["sequence"] != expectedSequence) return false;
            if (item is null) throw new InvalidOperationException("Unknown message for recipient");
            // A cancellation that suppressed this queued input won the admission race.
            if ((string?)assignments[id]?["delivery"] == "suppressed") return false;
            item["error"] = reason;
            item["delivered"] = true;
            var sequence = next;
            var trimmed = trimmedThrough;
            if (notify is not null)
            {
                var noticeId = "failure-" + Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(id)));
                if (!copy.OfType<JsonObject>().Any(e => (string?)e["id"] == noticeId))
                {
                    // Terminalizing the failed entry and enqueuing its notice commit together.
                    // At capacity the failed entry itself may be the oldest evictable history.
                    while (copy.Count >= capacity)
                    {
                        var evict = copy.OfType<JsonObject>().First(e => (bool?)e["delivered"] == true);
                        trimmed = Math.Max(trimmed, (long)evict["sequence"]!);
                        copy.Remove(evict);
                    }
                    copy.Add((JsonNode)new JsonObject { ["id"] = noticeId, ["sequence"] = ++sequence, ["sender"] = "service", ["recipient"] = notify,
                        ["text"] = $"Delivery notice for message_id {id} to {recipient}: {reason}\nThis is a service notice; no reply is required.", ["delivered"] = false });
                }
            }
            var disposition = uncertain && (bool?)item["started"] == true ? "uncertain" : "failed";
            Save(copy, sequence, trimmed, WithWaitDelivery(item, disposition), WithAssignmentDelivery(id, disposition));
            return true;
        }
    }

    void SetFlag(string id, string recipient, string flag)
    {
        lock (gate)
        {
            var copy = entries.DeepClone().AsArray();
            var item = copy.OfType<JsonObject>().FirstOrDefault(e => (string?)e["id"] == id && (string?)e["recipient"] == recipient)
                ?? throw new InvalidOperationException("Unknown message for recipient");
            if ((bool?)item[flag] == true) return;
            item[flag] = true;
            Save(copy, next, waits: WithWaitDelivery(item, flag == "started" ? "handoff_started" : "delivered"),
                assigned: WithAssignmentDelivery(id, flag == "started" ? "started" : "delivered"));
        }
    }

    void Save(JsonArray replacement, long sequence, long? trimmed = null, JsonObject? waits = null, JsonObject? assigned = null)
    {
        var root = new JsonObject { ["next"] = sequence, ["entries"] = replacement, ["trimmedThrough"] = trimmed ?? trimmedThrough };
        if (waits is not null || replyWaits.Count > 0) root["replyWaits"] = waits ?? replyWaits.DeepClone();
        if (assigned is not null || assignments.Count > 0) root["assignments"] = assigned ?? assignments.DeepClone();
        WriteFile(path, root.ToJsonString());
        entries = root["entries"]!.AsArray();
        if (waits is not null) replyWaits = waits;
        if (assigned is not null) assignments = assigned;
        next = sequence;
        trimmedThrough = trimmed ?? trimmedThrough;
    }
}
