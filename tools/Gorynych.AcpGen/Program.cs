// Generates the ACP v1 protocol types of Gorynych.Acp from the official JSON schema release.
//
//   dotnet run --project tools/Gorynych.AcpGen [-- <repo root> <schema version>]
//
// Reads schema/acp/<version>/schema.json and meta.json and writes
// src/Gorynych.Acp/Generated/Acp.g.cs. The mapping rules are documented in docs/acp-types.md.
using System.Text;
using System.Text.Json.Nodes;

var root = args.Length > 0 ? Path.GetFullPath(args[0]) : FindRepoRoot();
var version = args.Length > 1 ? args[1] : "v1.29.1";
var schemaDir = Path.Combine(root, "schema", "acp", version);
var schema = JsonNode.Parse(File.ReadAllText(Path.Combine(schemaDir, "schema.json")))!.AsObject();
var meta = JsonNode.Parse(File.ReadAllText(Path.Combine(schemaDir, "meta.json")))!.AsObject();
var output = Path.Combine(root, "src", "Gorynych.Acp", "Generated", "Acp.g.cs");
var code = new Generator(schema, meta, version).Run();
File.WriteAllText(output, code.ReplaceLineEndings("\n"));
Console.WriteLine($"wrote {output} ({code.Length} chars)");

static string FindRepoRoot()
{
    for (var dir = new DirectoryInfo(Environment.CurrentDirectory); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "Gorynych.slnx"))) return dir.FullName;
    throw new InvalidOperationException("Run from inside the repository or pass its root.");
}

/// <summary>A property of a generated class.</summary>
sealed record Prop(string JsonName, JsonObject Schema, bool Required);

/// <summary>One variant of a discriminated union.</summary>
sealed record Variant(string? Tag, string ClassName, List<Prop> Props, bool ReusesDef);

abstract record Shape;
/// <summary>Maps to a plain C# type (string, long, JsonNode...).</summary>
sealed record AliasShape(string CsType, bool IsValueType) : Shape;
sealed record EnumShape(List<string> Values) : Shape;
sealed record ClassShape(List<Prop> Props) : Shape;
sealed record UnionShape(string Discriminator, List<Prop> BaseProps, List<Variant> Variants) : Shape;

sealed class Generator(JsonObject schema, JsonObject meta, string version)
{
    // Message envelopes are handled by the JSON-RPC layer, extension payloads stay raw JSON.
    static readonly HashSet<string> Envelopes =
        ["AgentRequest", "AgentNotification", "ClientRequest", "ClientNotification", "AgentResponse", "ClientResponse"];
    static readonly HashSet<string> RawDefs = ["ExtRequest", "ExtResponse", "ExtNotification"];

    readonly JsonObject defs = schema["$defs"]!.AsObject();
    readonly Dictionary<string, int> refCounts = [];
    readonly Dictionary<string, Shape> shapes = [];
    /// <summary>Defs that became a variant of a union: def name -> (base, tag).</summary>
    readonly Dictionary<string, (string Base, string? Tag)> derived = [];
    readonly StringBuilder sb = new();

    public string Run()
    {
        foreach (var (name, def) in defs)
            if (!Envelopes.Contains(name)) CountRefs(def);
        foreach (var (name, _) in defs)
            if (!Envelopes.Contains(name)) ShapeOf(name);

        Line("// <auto-generated>");
        Line($"// Generated by tools/Gorynych.AcpGen from the Agent Client Protocol schema {version}");
        Line("// (https://github.com/agentclientprotocol/agent-client-protocol/releases). Do not edit.");
        Line("// </auto-generated>");
        Line("#nullable enable");
        Line("#pragma warning disable CS1591");
        Line("using System.Text.Json;");
        Line("using System.Text.Json.Nodes;");
        Line("using System.Text.Json.Serialization;");
        Line();
        Line("namespace Gorynych.Acp;");
        Line();
        EmitMethods();
        var serializable = new List<string>();
        foreach (var (name, def) in defs)
        {
            if (Envelopes.Contains(name) || derived.ContainsKey(name)) continue;
            switch (shapes[name])
            {
                case EnumShape e: EmitEnum(name, def!.AsObject(), e); break;
                case ClassShape c: EmitClass(name, def!.AsObject(), c.Props, null, null); serializable.Add(name); break;
                case UnionShape u: EmitUnion(name, def!.AsObject(), u, serializable); break;
            }
        }
        EmitContext(serializable);
        return sb.ToString();
    }

    // ---------------------------------------------------------------- analysis

    void CountRefs(JsonNode? node)
    {
        switch (node)
        {
            case JsonObject o:
                foreach (var (k, v) in o)
                {
                    if (k == "$ref" && v is JsonValue r) refCounts[RefName(r.GetValue<string>())] = refCounts.GetValueOrDefault(RefName(r.GetValue<string>())) + 1;
                    else CountRefs(v);
                }
                break;
            case JsonArray a:
                foreach (var v in a) CountRefs(v);
                break;
        }
    }

    static string RefName(string r) => r.StartsWith("#/$defs/", StringComparison.Ordinal) ? r["#/$defs/".Length..] : throw new NotSupportedException(r);

    Shape ShapeOf(string name)
    {
        if (shapes.TryGetValue(name, out var known)) return known;
        var def = defs[name]!.AsObject();
        Shape shape;
        if (RawDefs.Contains(name)) shape = new AliasShape("JsonNode", false);
        else if (name == "ErrorCode") shape = new AliasShape("int", true);
        else shape = Analyze(name, def);
        shapes[name] = shape;
        return shape;
    }

    Shape Analyze(string name, JsonObject def)
    {
        var union = (def["oneOf"] ?? def["anyOf"]) as JsonArray;
        if (union is not null)
        {
            var variants = union.Select(v => v!.AsObject()).ToList();
            if (variants.All(v => Str(v["type"]) == "string"))
                return new EnumShape(variants.Select(v => Str(v["const"])).OfType<string>().ToList());
            var disc = Str(def["discriminator"]?["propertyName"]) ?? DetectDiscriminator(variants);
            if (disc is not null)
                return BuildUnion(name, def, disc, variants);
            if (def["properties"] is null && variants.All(IsRefOnly))
            {
                // Untagged union of objects: one class with every variant's properties, all optional.
                var props = new List<Prop>();
                foreach (var v in variants) CollectProps(v, props, forceOptional: true, exclude: null);
                return new ClassShape(props);
            }
            if (def["properties"] is null)
                return new AliasShape("JsonNode", false);
        }
        var type = def["type"];
        if (def["properties"] is not null || Str(type) == "object")
        {
            var props = new List<Prop>();
            CollectProps(def, props, forceOptional: false, exclude: null);
            return new ClassShape(props);
        }
        return Str(type) switch
        {
            "string" => new AliasShape("string", false),
            "boolean" => new AliasShape("bool", true),
            "integer" => new AliasShape(IntType(Str(def["format"])), true),
            "number" => new AliasShape("double", true),
            _ => new AliasShape("JsonNode", false),
        };
    }

    static bool IsRefOnly(JsonObject v) =>
        v["properties"] is null && v["allOf"] is JsonArray a && a.Count == 1 && a[0]?["$ref"] is not null;

    static string? DetectDiscriminator(List<JsonObject> variants)
    {
        foreach (var v in variants)
            if (v["properties"] is JsonObject p)
                foreach (var (k, prop) in p)
                    if (prop?["const"] is not null) return k;
        return null;
    }

    UnionShape BuildUnion(string name, JsonObject def, string disc, List<JsonObject> variants)
    {
        var baseProps = new List<Prop>();
        CollectProps(def, baseProps, forceOptional: false, exclude: disc, includeUnion: false);
        var result = new List<Variant>();
        foreach (var v in variants)
        {
            var tag = Str(v["properties"]?[disc]?["const"]);
            var title = Str(v["title"]);
            if (tag is null && (title == "other" || v["not"] is not null)) continue; // caught by Unknown
            var label = tag ?? title ?? throw new NotSupportedException($"{name}: untitled default variant");
            var ownProps = v["properties"] is JsonObject vp ? vp.Count(kv => kv.Key != disc) : 0;
            var refs = (v["allOf"] as JsonArray)?.Select(a => Str(a?["$ref"])).OfType<string>().Select(RefName).ToList() ?? [];
            if (ownProps == 0 && v["anyOf"] is null && refs.Count == 1 && refCounts.GetValueOrDefault(refs[0]) == 1
                && ShapeOf(refs[0]) is ClassShape reused)
            {
                derived[refs[0]] = (name, tag);
                var props = reused.Props.Where(p => baseProps.All(b => b.JsonName != p.JsonName)).ToList();
                result.Add(new Variant(tag, refs[0], props, ReusesDef: true));
            }
            else
            {
                var props = new List<Prop>();
                CollectProps(v, props, forceOptional: false, exclude: disc);
                props.RemoveAll(p => baseProps.Any(b => b.JsonName == p.JsonName));
                var className = name + Pascal(label);
                if (defs.ContainsKey(className)) className += "Variant";
                result.Add(new Variant(tag, className, props, ReusesDef: false));
            }
        }
        return new UnionShape(disc, baseProps, result);
    }

    /// <summary>Collects the properties of an object schema, following allOf references and untagged anyOf mixins.</summary>
    void CollectProps(JsonObject s, List<Prop> into, bool forceOptional, string? exclude, bool includeUnion = true)
    {
        var required = (s["required"] as JsonArray)?.Select(r => r!.GetValue<string>()).ToHashSet() ?? [];
        if (s["properties"] is JsonObject props)
            foreach (var (k, p) in props)
                if (k != exclude && into.All(x => x.JsonName != k))
                    into.Add(new Prop(k, p!.AsObject(), !forceOptional && required.Contains(k)));
        if (s["allOf"] is JsonArray all)
            foreach (var a in all)
                if (Str(a?["$ref"]) is { } r)
                {
                    var target = defs[RefName(r)]!.AsObject();
                    CollectProps(target, into, forceOptional, exclude);
                }
        if (includeUnion && (s["anyOf"] ?? s["oneOf"]) is JsonArray mix && mix.Select(m => m!.AsObject()).All(IsRefOnly))
            foreach (var m in mix)
                CollectProps(m!.AsObject(), into, forceOptional: true, exclude);
    }

    // ---------------------------------------------------------------- type mapping

    /// <summary>Returns the C# type of a property schema, without nullability, and whether it is a value type.</summary>
    (string Type, bool IsValue) TypeOf(JsonObject p)
    {
        if (Str(p["$ref"]) is { } direct) return TypeOfDef(RefName(direct));
        if (p["allOf"] is JsonArray all && all.Count == 1 && Str(all[0]?["$ref"]) is { } r) return TypeOfDef(RefName(r));
        if (p["anyOf"] is JsonArray any)
        {
            var nonNull = any.Where(a => Str(a?["type"]) != "null").Select(a => a!.AsObject()).ToList();
            if (nonNull.Count == 1) return TypeOf(nonNull[0]);
            return ("JsonNode", false);
        }
        var type = p["type"] switch
        {
            JsonArray arr => arr.Select(Str).FirstOrDefault(t => t != "null"),
            var t => Str(t),
        };
        switch (type)
        {
            case "string": return ("string", false);
            case "boolean": return ("bool", true);
            case "integer": return (IntType(Str(p["format"])), true);
            case "number": return ("double", true);
            case "array":
                var item = p["items"] is JsonObject io ? TypeOf(io).Type : "JsonNode";
                return ($"List<{item}>", false);
            case "object":
                if (p["additionalProperties"] is JsonObject ap) return ($"Dictionary<string, {Nullable(TypeOf(ap))}>", false);
                return ("JsonObject", false);
            default: return ("JsonNode", false);
        }
    }

    (string, bool) TypeOfDef(string name) => ShapeOf(name) switch
    {
        AliasShape a => (a.CsType, a.IsValueType),
        EnumShape => (name, true),
        _ => (name, false),
    };

    static string Nullable((string Type, bool IsValue) t) => t.Type + "?";

    static string IntType(string? format) => format switch
    {
        "int32" => "int",
        "uint32" => "uint",
        "uint16" => "ushort",
        "uint8" => "byte",
        "uint64" => "ulong",
        _ => "long",
    };

    // ---------------------------------------------------------------- emission

    void EmitMethods()
    {
        Summary("ACP method names and versions from the schema release's meta.json.");
        Line("public static class AcpMethods");
        Line("{");
        Line($"    public const int ProtocolVersion = {meta["version"]!.GetValue<int>()};");
        Line($"    public const string SchemaVersion = \"{version}\";");
        foreach (var (group, cls) in new[] { ("agentMethods", "Agent"), ("clientMethods", "Client"), ("protocolMethods", "Protocol") })
        {
            Line();
            Line($"    public static class {cls}");
            Line("    {");
            foreach (var (k, v) in meta[group]!.AsObject())
                Line($"        public const string {Pascal(k)} = \"{v!.GetValue<string>()}\";");
            Line("    }");
        }
        Line("}");
        Line();
    }

    void EmitEnum(string name, JsonObject def, EnumShape e)
    {
        Summary(Str(def["description"]));
        Line($"[JsonConverter(typeof(OpenEnumJsonConverter<{name}>))]");
        Line($"public readonly partial record struct {name}(string Value) : IOpenEnum<{name}>");
        Line("{");
        var variants = ((def["oneOf"] ?? def["anyOf"]) as JsonArray)!;
        foreach (var v in variants)
        {
            var c = Str(v?["const"]);
            if (c is null) continue;
            Summary(Str(v?["description"]), "    ");
            Line($"    public static {name} {Pascal(c)} {{ get; }} = new(\"{c}\");");
        }
        Line($"    public static {name} Create(string value) => new(value);");
        Line("    public override string ToString() => Value;");
        Line("}");
        Line();
    }

    void EmitClass(string name, JsonObject def, List<Prop> props, string? baseName, Variant? variant, bool isAbstractBase = false)
    {
        Summary(Str(def["description"]));
        if (Str(def["x-method"]) is { } method)
            Line($"/// <remarks>Method <c>{method}</c>, {Str(def["x-side"])} side.</remarks>");
        var modifiers = isAbstractBase ? "public abstract partial class" : "public sealed partial class";
        Line(baseName is null ? $"{modifiers} {name}" : $"{modifiers} {name} : {baseName}");
        Line("{");
        if (variant is not null)
            Line($"    public {name}() : base({(variant.Tag is null ? "null" : $"\"{variant.Tag}\"")}) {{ }}");
        foreach (var p in props) EmitProp(name, p);
        Line("}");
        Line();
    }

    void EmitProp(string owner, Prop p)
    {
        var (type, isValue) = TypeOf(p.Schema);
        var csName = p.JsonName == "_meta" ? "Meta" : Pascal(p.JsonName);
        if (csName == owner) csName += "Value";
        Summary(Str(p.Schema["description"]), "    ");
        Line($"    [JsonPropertyName(\"{p.JsonName}\")]");
        if (!p.Required)
        {
            Line($"    public {type}? {csName} {{ get; set; }}");
            return;
        }
        var init = isValue ? "" : type.StartsWith("List<", StringComparison.Ordinal) ? " = [];" : type == "string" ? " = \"\";" : " = null!;";
        Line($"    public {type} {csName} {{ get; set; }}{init}");
    }

    void EmitUnion(string name, JsonObject def, UnionShape u, List<string> serializable)
    {
        Summary(Str(def["description"]));
        if (Str(def["x-method"]) is { } method)
            Line($"/// <remarks>Method <c>{method}</c>, {Str(def["x-side"])} side. Discriminated by <c>{u.Discriminator}</c>.</remarks>");
        else
            Line($"/// <remarks>Discriminated by <c>{u.Discriminator}</c>; unknown variants deserialize to <see cref=\"Unknown\"/>.</remarks>");
        Line($"[JsonConverter(typeof({name}JsonConverter))]");
        Line($"public abstract partial class {name}");
        Line("{");
        Line($"    private protected {name}(string? tag) {{ Tag = tag; }}");
        Line();
        Line($"    /// <summary>The <c>{u.Discriminator}</c> value of this variant; null for the variant that has none.</summary>");
        Line("    [JsonIgnore] public string? Tag { get; }");
        foreach (var p in u.BaseProps) EmitProp(name, p);
        Line();
        Line("    /// <summary>A variant this schema version does not know; keeps the raw JSON so it can be forwarded unchanged.</summary>");
        Line($"    public sealed class Unknown(string? tag, JsonObject raw) : {name}(tag)");
        Line("    {");
        Line("        [JsonIgnore] public JsonObject Raw { get; } = raw;");
        Line("    }");
        Line("}");
        Line();
        foreach (var v in u.Variants)
        {
            var vdef = v.ReusesDef ? defs[v.ClassName]!.AsObject() : new JsonObject();
            EmitClass(v.ClassName, vdef, v.Props, name, v);
            serializable.Add(v.ClassName);
        }

        var defaultVariant = u.Variants.FirstOrDefault(v => v.Tag is null);
        Line($"internal sealed class {name}JsonConverter : JsonConverter<{name}>");
        Line("{");
        Line($"    public override {name}? Read(ref Utf8JsonReader reader, Type typeToConvert, JsonSerializerOptions options)");
        Line("    {");
        Line("        if (reader.TokenType == JsonTokenType.Null) return null;");
        Line($"        var obj = JsonNode.Parse(ref reader) as JsonObject ?? throw new JsonException(\"{name} must be a JSON object.\");");
        Line($"        var tag = AcpJson.GetTag(obj, \"{u.Discriminator}\");");
        Line("        return tag switch");
        Line("        {");
        foreach (var v in u.Variants.Where(v => v.Tag is not null))
            Line($"            \"{v.Tag}\" => obj.Deserialize(AcpJsonContext.Default.{v.ClassName}),");
        if (defaultVariant is not null)
            Line($"            null => obj.Deserialize(AcpJsonContext.Default.{defaultVariant.ClassName}),");
        Line($"            _ => new {name}.Unknown(tag, obj),");
        Line("        };");
        Line("    }");
        Line();
        Line($"    public override void Write(Utf8JsonWriter writer, {name} value, JsonSerializerOptions options)");
        Line("    {");
        Line("        JsonNode? body = value switch");
        Line("        {");
        Line($"            {name}.Unknown u => u.Raw,");
        foreach (var v in u.Variants)
            Line($"            {v.ClassName} x => JsonSerializer.SerializeToNode(x, AcpJsonContext.Default.{v.ClassName}),");
        Line($"            _ => throw new JsonException($\"Unsupported {name} variant {{value.GetType()}}.\"),");
        Line("        };");
        Line($"        AcpJson.WriteTagged(writer, \"{u.Discriminator}\", value is {name}.Unknown ? null : value.Tag, body);");
        Line("    }");
        Line("}");
        Line();
    }

    void EmitContext(List<string> serializable)
    {
        Summary("Source-generated System.Text.Json metadata for every ACP type, so serialization works under Native AOT.");
        Line("[JsonSourceGenerationOptions(DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull)]");
        foreach (var name in serializable.Distinct())
            Line($"[JsonSerializable(typeof({name}))]");
        foreach (var (name, shape) in shapes)
            if (shape is UnionShape) Line($"[JsonSerializable(typeof({name}))]");
        Line("[JsonSerializable(typeof(JsonNode))]");
        Line("[JsonSerializable(typeof(JsonObject))]");
        Line("[JsonSerializable(typeof(JsonElement))]");
        Line("public sealed partial class AcpJsonContext : JsonSerializerContext;");
    }

    // ---------------------------------------------------------------- helpers

    void Summary(string? text, string indent = "")
    {
        if (string.IsNullOrWhiteSpace(text)) return;
        var escaped = text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
        Line($"{indent}/// <summary>");
        foreach (var l in escaped.ReplaceLineEndings("\n").Split('\n'))
            Line($"{indent}/// {l}".TrimEnd());
        Line($"{indent}/// </summary>");
    }

    void Line(string s = "") => sb.Append(s).Append('\n');

    static string? Str(JsonNode? n) => n is JsonValue v && v.TryGetValue<string>(out var s) ? s : null;

    static string Pascal(string s)
    {
        var b = new StringBuilder();
        var upper = true;
        foreach (var ch in s)
        {
            if (ch is '_' or '-' or '/' or '.' or ' ' or '$') { upper = true; continue; }
            b.Append(upper ? char.ToUpperInvariant(ch) : ch);
            upper = false;
        }
        return b.ToString();
    }
}
